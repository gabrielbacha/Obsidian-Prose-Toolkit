import esbuild from "esbuild";
import { readFileSync } from "node:fs";
import process from "node:process";
import path from "node:path";
import { builtinModules } from "node:module";

const notice = readFileSync("THIRD_PARTY_NOTICES.md", "utf8").trim();
const banner = "/*\nTHIS IS A GENERATED/BUNDLED FILE BY ESBUILD.\n" +
	"Source: https://github.com/gabrielbacha/Obsidian-Prose-Toolkit\n" +
	notice.replaceAll("*/", "* /") + "\n*/";

const production = process.argv[2] === "production";
const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	plugins: [{
		name: "local-text-worker",
		setup(build) {
			build.onResolve({ filter: /^prose-toolkit:worker$/ }, () => ({ path: "text-worker", namespace: "local-worker" }));
			build.onLoad({ filter: /.*/, namespace: "local-worker" }, async () => {
				const worker = await esbuild.build({ entryPoints: ["src/text-worker.ts"], bundle: true, platform: "browser", format: "iife", target: "es2021", minify: production, write: false, metafile: true });
				return { contents: "export default " + JSON.stringify(worker.outputFiles[0].text) + ";", loader: "js", watchFiles: Object.keys(worker.metafile.inputs).map((file) => path.resolve(file)) };
			});
		},
	}],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: production,
});

if (production) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}

